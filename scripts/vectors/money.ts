/** Every text against every currency (and every mode when `modes`). */
function grid(texts: readonly string[], modes: boolean): CaseSpec[] {
  const out: CaseSpec[] = []
  for (const c of ALL) {
    for (const t of texts) {
      if (modes) for (const m of MODES) out.push([`${c} ${m} ${JSON.stringify(t)}`, [t, c, m]])
      else out.push([`${c} ${JSON.stringify(t)}`, [t, c]])
    }
  }
  return out
}

