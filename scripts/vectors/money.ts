/** Cases the exact limit of asksOver sits between: found by the same function, so the pair is the edge. */
function limitPairs(): CaseSpec[] {
  const edges: Array<[number, Currency, number | undefined, number, string]> = [
    [100_000, 'KRW', 150_000_000, 0, 'KRW 100,000 at 150,000,000'],
    [10_000, 'USD', 100_000, 0, 'USD $100 at 100,000'],
    [190, 'USD', 100_000, 0, 'USD $1.90 at 100,000'],
    [1_000_000, 'JPY', 15_000_000, 2, 'JPY 1,000,000 at 15,000,000 +2%'],
    [100_000, 'KRW', 150_000_000, -50, 'KRW 100,000 at 150,000,000 -50%'],
    [10_000, 'USD', 99_999.5, 0, 'USD $100 at 99,999.5'],
    [1, 'KRW', 1, 0, 'KRW 1 at rate 1'],
    [MAX_MINOR, 'KRW', 150_000_000, 1.5, 'KRW MAX_MINOR at 150,000,000 +1.5%'],
    [99_999_999_999, 'USD', 71_926.12, -2.25, 'USD max cents at 71,926.12 -2.25%'],
    [50_000, 'JPY', 11_511_750.123456, 0.0001, 'JPY 50,000 at a rate with six decimals, +0.0001%'],
  ]
  const out: CaseSpec[] = []
  for (const [bound, cur, rate, fee, label] of edges) {
    let lo = 0
    let hi = 1
    while (!asksOver(hi, bound, cur, rate, fee) && hi < Number.MAX_SAFE_INTEGER / 2) hi *= 2
    while (hi - lo > 1) {
      const mid = Math.floor((lo + hi) / 2)
      if (asksOver(mid, bound, cur, rate, fee)) hi = mid
      else lo = mid
    }
    out.push([`limit ${label}: ${hi - 1} sats`, [hi - 1, bound, cur, rate, fee]], [`limit ${label}: ${hi} sats`, [hi, bound, cur, rate, fee]])
  }
  return out
}

